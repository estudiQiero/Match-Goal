// Tildes: letra base + marca encima (dos filas por encima de la letra).
const ACCENT = { 'Á': 'A', 'É': 'E', 'Í': 'I', 'Ó': 'O', 'Ú': 'U', 'Ü': 'U', 'Ñ': 'N' };
const MARK = {
  acute: ['...#.', '..#..'],
  tilde: ['.##.#', '#.##.'],
  dier: ['.#.#.', '.....'],
};
const markFor = ch => ch === 'Ñ' ? MARK.tilde : ch === 'Ü' ? MARK.dier : MARK.acute;

const SPACE = 3, GAP = 1;
const glyphWidth = ch => ch === ' ' ? SPACE : (G[ACCENT[ch] || ch] || G['?'])[0].length;

// Ancho del texto en píxeles de letra.
export function pixelTextWidth(text) {
  const s = text.toUpperCase();
  let w = 0;
  for (let i = 0; i < s.length; i++) w += glyphWidth(s[i]) + (i < s.length - 1 ? GAP : 0);
  return w;
}

// Dibuja el texto centrado en (cx, cy) con píxeles de tamaño px (en px de pantalla).
export function drawPixelText(c, text, cx, cy, px, color) {
  const s = text.toUpperCase();
  px = Math.max(1, Math.round(px));
  const w = pixelTextWidth(s) * px;
  let x = Math.round(cx - w / 2);
  const y = Math.round(cy - 3.5 * px);
  const cells = [];
  for (const ch of s) {
    if (ch === ' ') { x += (SPACE + GAP) * px; continue; }
    const base = ACCENT[ch] || ch, g = G[base] || G['?'];
    g.forEach((row, r) => { for (let i = 0; i < row.length; i++) if (row[i] === '#') cells.push([x + i * px, y + r * px]); });
    if (ACCENT[ch]) {
      const m = markFor(ch), off = Math.floor((g[0].length - 5) / 2);
      m.forEach((row, r) => { for (let i = 0; i < row.length; i++) if (row[i] === '#') cells.push([x + (i + off) * px, y + (r - 3) * px]); });
    }
    x += (g[0].length + GAP) * px;
  }
  // Sombra tenue de un píxel hacia abajo (no es contorno).
  c.fillStyle = 'rgba(0,0,0,0.22)';
  for (const [a, b] of cells) c.fillRect(a, b + px, px, px);
  c.fillStyle = color;
  for (const [a, b] of cells) c.fillRect(a, b, px, px);
}
